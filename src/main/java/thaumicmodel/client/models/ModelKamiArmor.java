    private void checkSet(Entity entity) {
        if (entity instanceof EntityLivingBase && entity.ticksExisted % 20 == 0) {
            int set = 0;

            for(int a = 1; a < 5; ++a) {
                ItemStack piece = ((EntityLivingBase)entity).getItemStackFromSlot(EntityEquipmentSlot.values()[a + 1]);
                if (piece != null && piece.getItem() instanceof ItemKamiArmor) {
                    ++set;
                    switch (a) {
                        case 1:
                            this.GemBoots.isHidden = piece.getItemDamage() == 1;
                            break;
                        case 2:
                            this.GemLegs.isHidden = piece.getItemDamage() == 1;
                            break;
                        case 3:
                            this.GemBody.isHidden = piece.getItemDamage() == 1;
                            break;
                        case 4:
                            this.GemHead.isHidden = piece.getItemDamage() == 1;
                    }
                }
            }

            if (set > 0) {
                hasSet.put(entity.getEntityId(), set);
            } else {
                hasSet.remove(entity.getEntityId());
            }
        }

    }

    public void render(Entity entity, float f, float f1, float f2, float f3, float f4, float f5) {
        this.checkSet(entity);
        this.setRotationHarness(entity);
        int set = hasSet.containsKey(entity.getEntityId()) ? (Integer)hasSet.get(entity.getEntityId()) : -1;
        this.Tier2Head.isHidden = set < 2;
        this.Tier3Head.isHidden = set < 3;
        this.Tier4Head.isHidden = set < 4;
        this.LeftArmTier2.isHidden = set < 2;
        this.LeftArmTier3.isHidden = set < 3;
        this.LeftArmTier4.isHidden = set < 4;
        this.RightArmTier2.isHidden = set < 2;
        this.RightArmTier3.isHidden = set < 3;
        this.RightArmTier4.isHidden = set < 4;
        this.LeftLegTier2.isHidden = set < 2;
        this.LeftLegTier3.isHidden = set < 3;
        this.RightLegTier2.isHidden = set < 2;
        this.RightLegTier3.isHidden = set < 3;
        this.HipTier4.isHidden = set < 4;
        super.render(entity, f, f1, f2, f3, f4, f5);
    }

    public void setRotationAngle(ModelRenderer modelRenderer, float x, float y, float z) {
        modelRenderer.rotateAngleX = x;
        modelRenderer.rotateAngleY = y;
        modelRenderer.rotateAngleZ = z;
    }

    public void setRotationHarness(Entity entity) {
        if (entity != null && entity instanceof EntityPlayer) {
            EntityPlayer player = (EntityPlayer)entity;
            if (player.capabilities.isFlying) {
                this.HarnesssLight.isHidden = false;
                ModelRenderer var10000 = this.HarnesssLight;
                var10000.rotateAngleZ += 5.0F;
            } else {
                this.HarnesssLight.isHidden = true;
            }
        }

    }
